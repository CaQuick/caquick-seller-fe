import { type JosaPair, josa, withJosa } from './josa';

const PAIRS: JosaPair[] = ['을/를', '이/가', '은/는', '와/과', '으로/로'];

describe('withJosa', () => {
  // 받침 없음 / 받침 있음(ㄹ 제외) / ㄹ 받침 × 조사 다섯 쌍 전수
  it.each([
    ['리뷰', ['리뷰를', '리뷰가', '리뷰는', '리뷰와', '리뷰로']],
    ['상품', ['상품을', '상품이', '상품은', '상품과', '상품으로']],
    ['매장', ['매장을', '매장이', '매장은', '매장과', '매장으로']],
    ['케이크', ['케이크를', '케이크가', '케이크는', '케이크와', '케이크로']],
    ['서울', ['서울을', '서울이', '서울은', '서울과', '서울로']],
    ['댓글', ['댓글을', '댓글이', '댓글은', '댓글과', '댓글로']],
    [
      '점검 케이크샵',
      [
        '점검 케이크샵을',
        '점검 케이크샵이',
        '점검 케이크샵은',
        '점검 케이크샵과',
        '점검 케이크샵으로',
      ],
    ],
  ])('%s → %j', (word, expected) => {
    expect(PAIRS.map((p) => withJosa(word, p))).toEqual(expected);
  });

  // 숫자는 끝자리(또는 끝의 자리 이름)를 읽는 소리로 판별한다
  it.each([
    ['0', '을', '으로'], // 영
    ['1', '을', '로'], // 일(ㄹ)
    ['2', '를', '로'], // 이
    ['3', '을', '으로'], // 삼
    ['4', '를', '로'], // 사
    ['5', '를', '로'], // 오
    ['6', '을', '으로'], // 육
    ['7', '을', '로'], // 칠(ㄹ)
    ['8', '을', '로'], // 팔(ㄹ)
    ['9', '를', '로'], // 구
    ['10', '을', '으로'], // 십
    ['20', '을', '으로'], // 이십
    ['100', '을', '으로'], // 백
    ['1,000', '을', '으로'], // 천
    ['10000', '을', '으로'], // 만
    ['300000000', '을', '으로'], // 삼억
    ['1000000000000000', '을', '으로'], // 천조
    ['1.5', '를', '로'], // 일 점 오
    ['1.50', '을', '으로'], // 일 점 오 영
    ['GS25', '를', '로'], // 이십오
    ['2층', '을', '으로'],
  ])('숫자 %s → %s / %s', (word, object, direction) => {
    expect(josa(word, '을/를')).toBe(object);
    expect(josa(word, '으로/로')).toBe(direction);
  });

  // 영문은 알파벳 이름으로 읽히는 경우만: 한 글자이거나 모음 없는 대문자 약어
  it.each([
    ['A', '를', '로'], // 에이
    ['B', '를', '로'],
    ['L', '을', '로'], // 엘(ㄹ)
    ['R', '을', '로'], // 알(ㄹ)
    ['M', '을', '으로'], // 엠
    ['N', '을', '으로'], // 엔
    ['x', '를', '로'], // 엑스
    ['SMS', '를', '로'], // 에스엠에스
    ['KFC', '를', '로'],
    ['HTML', '을', '로'],
    ['CGV', '를', '로'],
    ['케이크 A', '를', '로'],
  ])('영문 %s → %s / %s', (word, object, direction) => {
    expect(josa(word, '을/를')).toBe(object);
    expect(josa(word, '으로/로')).toBe(direction);
  });

  // 읽는 소리를 알 수 없으면 두 형태를 함께 쓴다
  it.each([
    ['cake'], // 단어 발음은 모른다
    ['Google'],
    ['LAB'], // 모음이 있는 대문자는 단어일 수 있다
    ['USB'],
    ['🎂'],
    ['#'],
    [''],
    ['   '],
    ['ㅋ'], // 자모만 있는 글자
    ['10000000000000000'], // 조를 넘는 수
  ])('판별 불가 %j → 을(를)·이(가)·은(는)·와(과)·(으)로', (word) => {
    expect(PAIRS.map((p) => josa(word, p))).toEqual([
      '을(를)',
      '이(가)',
      '은(는)',
      '와(과)',
      '(으)로',
    ]);
  });

  it.each([
    ['케이크(강남점)', '을'],
    ['"리뷰"', '를'],
    ['「서울」', '을'],
    ['상품 ', '을'],
  ])('끝의 닫는 괄호·따옴표·공백은 건너뛰고 판별한다: %s → %s', (word, expected) => {
    expect(josa(word, '을/를')).toBe(expected);
  });

  it('단어는 그대로 두고 조사만 붙인다', () => {
    expect(withJosa('케이크(강남점)', '을/를')).toBe('케이크(강남점)을');
  });
});
